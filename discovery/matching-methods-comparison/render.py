NAMES = {
    "keyword": "Keyword (TF-IDF cosine)",
    "keyword_phrase": "Keyword, tighter (cosine + shared phrase)",
    "anchor": "Shared named thing",
    "embedding": "Embedding similarity",
    "ai_judge": "AI judge",
    "embed_ai": "Embedding shortlist + AI",
}


def pct(x):
    return "n/a" if x is None else "%d%%" % round(100 * x)


def pci(x, ci):
    return "n/a" if x is None else "%s (%s to %s)" % (pct(x), pct(ci[0]), pct(ci[1]))


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def usd(x):
    return "n/a" if x is None else ("$%.5f" % x if x < 0.01 else "$%.2f" % x)


def secs(x):
    if x is None:
        return "n/a"
    return "%.4f s" % x if x < 0.1 else ("%.1f s" % x if x < 600 else "%.1f h" % (x / 3600))


def rule_text(R, m):
    th = R["thresholds"]
    lv = th.get(m)
    if m == "keyword":
        return "cosine at least %s" % lv if lv is not None else "no level calibrated"
    if m == "keyword_phrase":
        return "cosine at least %s and a shared phrase" % lv if lv is not None else "no level calibrated"
    if m == "anchor":
        return "at least %s shared named things" % lv if lv is not None else "no level calibrated"
    if m == "embedding":
        return "cosine at least %s" % lv if lv is not None else "NOT RUN or no level calibrated"
    if m == "ai_judge":
        return "AI reads real overlap and a speaker who may be an official"
    return "top %d pairs by embedding (cosine at least %s), then the AI rule" % (R["n_shortlist"], R["cutoff"] and round(R["cutoff"], 3))


