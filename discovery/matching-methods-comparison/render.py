def disagreement_lines(judge_labels, person, items, gold):
    L = []
    r, m = judge_labels.get("reader", {}), judge_labels.get("model", {})
    shared = sorted(set(r) & set(m))
    if shared:
        a = [r[p]["label"] for p in shared]
        b = [m[p]["label"] for p in shared]
        agree = sum(1 for x, y in zip(a, b) if x == y)
        kap = cl.cohen_kappa(a, b)
        L += ["Reader against language model on %d shared pairs: %d agree (kappa %s); the reader's file was "
              "reconciled with the model's, so this is an upper bound." % (len(shared), agree, "n/a" if kap is None else "%.2f" % kap), ""]
        diffs = cl.disagreements(r, m, key=lambda x: x["label"])
        L += table(["Pair", "Reader", "Model", "Reader's note"],
                   [[p, x, y, r[p].get("note", "")] for p, x, y in diffs])
        quotes = {cl.split_pair(p)[0] for p, _, _ in diffs}
        adjacent = all({x, y} in ({"topical", "meaningful"}, {"coincidental", "topical"}) for _, x, y in diffs)
        L += ["", "%d disagreements on %d different passages; %s." % (
            len(diffs), len(quotes), "every one is between neighbouring classes" if adjacent
            else "some separate classes that are not neighbours")]
        L += [""]
    if person:
        names = sorted(person)
        L += ["Person labelers: %s." % ", ".join(names), ""]
        for i, x in enumerate(names):
            for y in names[i + 1:]:
                both = sorted(set(person[x]) & set(person[y]))
                kap = cl.cohen_kappa([person[x][p] for p in both], [person[y][p] for p in both])
                L += ["- %s and %s: %d shared pairs, %d differ, kappa %s." % (
                    x, y, len(both), sum(1 for p in both if person[x][p] != person[y][p]),
                    "n/a" if kap is None else "%.2f" % kap)]
        L += [""]
    else:
        L += ["No person has labelled; the disagreement between people is not measured. Put labels in "
              "`data/person_labels/` (see its README) using `labelling-sheet.json`.", ""]
    bad = [it for it in items if it["kind"] == "labelled" and it["id"] in gold and rp.ai_ok(it)
           and it["ai"]["overlap"] != gold[it["id"]]["ready"]
           and not (gold[it["id"]]["ready"] == "none" and it["ai"]["overlap"] == "real"
                    and it["ai"]["speaker_type"] not in jd.ELIGIBLE_SPEAKERS)]
    if bad:
        L += ["AI judge against the labels, %d disagreements (the AI's own reason given):" % len(bad), ""]
        L += table(["Pair", "Label", "AI overlap", "AI speaker", "AI reason"],
                   [[it["id"], gold[it["id"]]["ready"], it["ai"]["overlap"], it["ai"]["speaker_type"],
                     it["ai"]["reason"]] for it in bad[:15]])
    return L


def _money_lines(R, donor, official):
    mon = R["money"].get(donor)
    if not mon:
        return ["  - Money: not retrieved."]
    if mon.get("error"):
        return ["  - Money: NOT RETRIEVED (%s)." % mon["error"]]
    rows = mon["rows"]
    mine = [x for x in rows if official and x.get("official") == official]
    pick = mine if mine else rows[:3]
    head = "committees of the proposed speaker" if mine else "largest committees (speaker not proposed or no match)"
    if not rows:
        return ["  - Money: no Schedule A rows by a contributor with this name in the committees tied to current "
                "officials (retrieved %s)." % R["money_date"]]
    out = ["  - Money (%s; Schedule A, matched by contributor name, retrieved %s; no cause implied):" % (head, R["money_date"])]
    for x in pick:
        out.append("    - %s to \"%s\" (%s, %s, %s; %d contributions, %s to %s)" % (
            cl.money(x["total"]), x["filer_name"], x.get("official", "?"), x.get("filer_type", "?"),
            x.get("status", "?"), x["n"], x["first"], x["last"]))
    return out


def pair_block(R, it):
    pr = R["priorities"][it["pi"]]
    flags = ", ".join("%s %s" % (m, {True: "proposes", False: "no", None: "not run"}[it["prop"][m]])
                      for m in rp.METHOD_ORDER)
    L = ["#### %s" % it["id"], ""]
    if it["qi"] is None:
        L += ["- Passage (synthetic probe, not a quote): %s" % it["text"]]
    else:
        q = R["quotes"][it["qi"]]
        L += ["- Quote, exact raw caption%s: \"%s\"" % (" with injected errors" if it["kind"] == "perturbed" else "", it["text"]),
              "- Meeting: %s, %s, caption stamp %s ([transcript](%s), retrieved %s)" % (
                  q["meeting_body"], q["meeting_date"], q["start"], q["url"], q["retrieved"])]
        sp = R["speakers"].get(it["qi"])
        if sp:
            L += ["- Speaker (a proposal only): %s; basis: %s; %s" % (sp["name"] or "none proposed", sp["basis"], sp["caution"])]
    L += ["- Priority (%s, section \"%s\"): \"%s\" ([source](%s), retrieved %s%s)" % (
        pr["donor"], pr.get("section") or "", pr["text"], pr["url"], pr["retrieved"],
        ", page dated " + pr["page_date"] if pr.get("page_date") else ""),
        "- Methods: %s" % flags]
    if it["id"] in R["gold"]:
        L += ["- Label: %s (review-ready), %s (overlap)" % (R["gold"][it["id"]]["ready"], R["gold"][it["id"]]["overlap"])]
    if rp.ai_ok(it):
        a = it["ai"]
        L += ["- AI reading: overlap %s, speaker type %s, stance %s. %s" % (a["overlap"], a["speaker_type"], a["stance"], a["reason"])]
    if it["qi"] is not None:
        sp = R["speakers"].get(it["qi"])
        L += _money_lines(R, pr["donor"], sp["name"] if sp else None)
    return L + [""]


def review_markdown(R, limit=6):
    items = [it for it in R["items"] if it["kind"] in ("labelled", "shortlist", "probe")]
    g = R["gold"]
    n = lambda it: sum(1 for m in rp.METHOD_ORDER if it["prop"][m])
    lab = [it for it in items if it["kind"] == "labelled" and it["id"] in g]
    sections = [
        ("Good matches: labelled real and proposed by two or more methods",
         sorted([it for it in lab if g[it["id"]]["ready"] == "real" and n(it) >= 2], key=lambda it: -n(it))),
        ("Misses: labelled real but not proposed by every method",
         sorted([it for it in lab if g[it["id"]]["ready"] == "real" and n(it) < len(rp.METHOD_ORDER)], key=n)),
        ("False matches: labelled no overlap but proposed",
         sorted([it for it in lab if g[it["id"]]["ready"] == "none" and n(it) >= 1], key=lambda it: -n(it))),
        ("Opposing positions that share topic words (the AI reads the stance as opposing)",
         sorted([it for it in items if it["kind"] != "probe" and rp.ai_ok(it) and it["ai"]["stance"] == "opposes"
                 and it["ai"]["overlap"] != "none"], key=lambda it: -n(it))),
        ("Opposite-side probes (synthetic)", [it for it in items if it["kind"] == "probe" and it["side"] == "opposite"]),
        ("Found by the embedding shortlist and the AI, not yet labelled",
         sorted([it for it in items if it["kind"] == "shortlist" and it["prop"]["embed_ai"]], key=lambda it: -it["emb"])),
    ]
    L = ["# Pairs for review: good matches, misses and false matches", "",
         "**Quotes are raw live captions (all capitals, unconfirmed against the recording); each speaker is a proposal.** "
         "Each pair shows the exact quote and its meeting, the cited priority with link and retrieval date, and the donor's "
         "reported money by committee. The money implies nothing about cause.", ""]
    for title, its in sections:
        L += ["## %s (%d; first %d shown)" % (title, len(its), limit), ""]
        for it in its[:limit]:
            L += pair_block(R, it)
    return "\n".join(L)


def labelling_sheet(R, n_random=20):
    picks = [it for it in R["items"] if it["kind"] in ("labelled", "shortlist")]
    picks += [it for it in R["items"] if it["kind"] == "random"][:n_random]
    picks.sort(key=lambda it: hashlib.md5(it["id"].encode()).hexdigest())
    out = []
    for it in picks:
        q, pr = R["quotes"][it["qi"]], R["priorities"][it["pi"]]
        out.append({"pair": it["id"],
                    "quote": {"meeting": "%s, %s" % (q["meeting_body"], q["meeting_date"]), "stamp": q["start"],
                              "url": q["url"], "text": q["text"]},
                    "priority": {"donor": pr["donor"], "section": pr.get("section"), "url": pr["url"],
                                 "retrieved": pr["retrieved"], "text": pr["text"]},
                    "label": None})
    return {"instructions": "Label each pair real (same specific measure, program, proposal or stated position), "
                            "loose (same broad subject only) or none. Read the caption as spoken; the speaker is not "
                            "known. Do not look at any method's or judge's output first.", "pairs": out}
