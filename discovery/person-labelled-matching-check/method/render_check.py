"""Markdown for results.md and matches-that-stand-out.md. Pure functions over the figures run.py computes."""

import check_lib as ck
import compare_lib as cl


def pct(x):
    return "n/a" if x is None else "%d%%" % round(100 * x)


def frac(s):
    """'k of n (share, range)' from check_lib.share()."""
    if s is None or not s["n"]:
        return "n/a (0 pairs)"
    lo, hi = s["ci"]
    return "%d of %d (%s; %s to %s)" % (s["k"], s["n"], pct(s["share"]), pct(lo), pct(hi))


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def rule(R, m):
    lv = R["thresholds"].get(m)
    if m == "keyword":
        return "cosine at least %s" % lv if lv is not None else "no level reaches chance under one"
    if m == "keyword_phrase":
        return "cosine at least %s and a shared rare phrase" % lv if lv is not None else "no level reaches chance under one"
    if m == "anchor":
        return "at least %s shared named things" % lv if lv is not None else "no level reaches chance under one"
    if m == "embedding":
        return "cosine at least %s" % lv if lv is not None else "NOT RUN, or no level reaches chance under one"
    if m == "ai_judge":
        return "the AI reads a real overlap and a speaker who may be an official, on the pool of %d pairs" % R["pool_size"]
    cut = R.get("cutoff")
    return "top %d pairs by embedding (cosine at least %s), then the AI rule" % (
        R["n_shortlist"], "n/a" if cut is None else round(cut, 3))


def chance_text(R, m):
    th = R["thresholds"]
    if m in ("keyword", "keyword_phrase", "anchor"):
        key = {"keyword": "keyword", "keyword_phrase": "keyword_phrase", "anchor": "anchor"}[m]
        lv = th.get(m)
        return "n/a" if lv is None else "%s" % R["lex_chance"][key].get(lv)
    if m == "embedding":
        lv = th.get(m)
        return "n/a" if lv is None else "%s" % R["emb_chance"].get(lv)
    if m == "embed_ai":
        c = R.get("cutoff_chance_upper")
        return "n/a" if c is None else "at most %s (the embedding's chance count at the shortlist's lowest score)" % c
    a = R["ai_null"]
    return ("not established: %d of %d random-word passages flagged, too few to bound a count over %s pairs"
            % (a["flagged"], a["pairs"], format(R["n_pairs"], ",")))


def results_markdown(R):
    L = ["# Person-labelled matching check: results (generated by method/run.py)", ""]
    people = R["people"]
    if people:
        L += ["**Labelled by people: %s; %d pairs labelled; every figure in sections 2 to 5 marked PERSON is against "
              "their consensus (the lower middle level where they differ).** Run on %s." % (
                  ", ".join(people), R["labelled_pairs"], R["run_date"]), ""]
    else:
        L += ["**No person has labelled yet.** Sections 2 to 5 hold nothing measured by a person; where a table is "
              "headed MACHINE it is the AI judge's reading, which is a language model's and not independent of the "
              "AI methods. The blind sheet to label is `labelling/label.html`. Run on %s." % R["run_date"], ""]
    if R["people_skipped"]:
        L += ["Label files not counted:", ""] + ["- " + s for s in R["people_skipped"]] + [""]
    if R["errors"]:
        L += ["## Stages that did not run", ""] + ["- **%s**: %s" % (k, v) for k, v in R["errors"].items()] + [""]

    L += ["## 0. Inputs", "",
          "- %d substantive caption passages from %d meetings, %d donor priority statements: %s pairs." % (
              R["n_quotes"], R["n_meetings"], R["n_priorities"], format(R["n_pairs"], ",")),
          "- Embedding model `%s`; AI judge `%s` (API version %s). Chance: %d random-word draws per model for the "
          "lexical methods (pooled and within meeting; the worse of the two is used); %d draws of %d random-word quotes "
          "for the embedding, scaled up to the corpus. Seed %d." % (
              R["embedding_model"], R["judge"]["model"], R["judge"]["api_version"], R["null_draws"],
              R["emb_null_draws"], R["emb_null_quotes"], R["seed"]), ""]

    L += ["## 1. The setting of each method and its chance count there", "",
          "A method's setting is the loosest level at which random-word quotes give fewer than one pair per run on "
          "average (the earlier trial's definition). `Pairs proposed` counts every proposal over the whole corpus, "
          "except the AI methods, which read only a pool (every lexical proposal, the top %d embedding proposals, the "
          "shortlist and %d random pairs)." % (R["emb_pool_cap"], R["n_random"]), ""]
    rows = []
    for m in ck.METHODS:
        n = R["proposal_counts"][m]
        rows.append([ck.NAMES[m], rule(R, m), "NOT RUN" if n is None else n, chance_text(R, m),
                     "yes" if R["chance_ok"].get(m) else "no"])
    L += table(["Method", "Setting", "Pairs proposed", "Chance pairs per run at that setting", "Chance under one?"], rows)
    L += ["", "Random pairs flagged (of %d drawn from all pairs, real quotes against real priorities): %s." % (
        R["n_random"], "; ".join("%s %d" % (ck.NAMES[m], v) for m, v in R["random_flagged"].items()) +
        "; AI judge %d" % R["random_ai_flagged"]), ""]
    for m, label in (("keyword", "Keyword (cosine)"), ("keyword_phrase", "Keyword, tighter (cosine with a shared phrase)"),
                     ("anchor", "Shared named things")):
        L += ["### Every setting: %s" % label, ""]
        L += table(["Level", "Pairs in the corpus", "Chance pairs per run (random words)"],
                   [[lv, R["lex_real"][m][lv], R["lex_chance"][m][lv]] for lv in R["lex_real"][m]]) + [""]
    if R["emb_real"]:
        L += ["### Every setting: embedding similarity (every fifth level)", ""]
        L += table(["Cosine", "Pairs in the corpus", "Chance pairs per run (random words)"],
                   [[lv, R["emb_real"][lv], R["emb_chance"][lv]] for lv in R["emb_real"] if round(lv * 100) % 5 == 0]) + [""]

    L += ["## 2. What share of each method's proposals a person judges real, and how many real ones it misses", ""]
    if R["person"]:
        rows = []
        for m in ck.METHODS:
            r = R["person"].get(m)
            if not r:
                rows.append([ck.NAMES[m], "NOT RUN", "", "", "", ""])
                continue
            est = r["estimated_real_among_proposals"]
            rows.append([ck.NAMES[m], r["proposals"], r["labelled_proposals"], frac(r["precision_real"]),
                         "n/a" if not est else "%d to %d" % (round(est["low"]), round(est["high"])),
                         "%d of %d known real" % (r["real_missed"], r["real_known"])])
        L += ["PERSON. Precision is real overlaps among a method's proposals that people labelled (the sheet draws "
              "%d proposals per method, so a method with more proposals than that is estimated from a sample; the "
              "estimate scales the 95%% range to all its proposals). A miss is a pair people judged real that the "
              "method does not propose; the known real overlaps are only those on the sheet, so the number of "
              "misses is a floor, not a count over all pairs." % (R["sheet"]["per_method"] or 0), ""]
        L += table(["Method", "Proposals", "Labelled", "Judged real (95% range)", "Estimated real among all proposals",
                    "Real overlaps missed"], rows) + [""]
        L += ["Judged loose or none, per method:", ""]
        L += table(["Method", "real", "loose", "none"],
                   [[ck.NAMES[m], r["real"], r["loose"], r["none"]] for m, r in R["person"].items()]) + [""]
    else:
        L += ["Not measured: no person has labelled. Per-method precision and misses against a person need "
              "`labelling/person_labels/*.json` from `labelling/label.html`.", ""]
    L += ["### MACHINE: the AI judge's reading of every proposal it read", "",
          "Not a person's label. `May be an official` is the AI's own speaker reading together with real overlap.", ""]
    rows = []
    for m in ck.METHODS:
        r = R["machine"].get(m)
        if r:
            rows.append([ck.NAMES[m], r["proposals"], r["read"], r["real"], r["loose"], r["none"],
                         r["real_and_may_be_official"]])
    L += table(["Method", "Proposals", "Read by the AI", "AI: real", "loose", "none", "real, may be an official"], rows) + [""]
    if R["ai_stats"]:
        s = R["ai_stats"]
        L += ["AI judge cost and time per pair read (this run's pool; %d calls, %d answered from cache): %.2f s, "
              "%d input and %d output tokens on average." % (s["read"], s["cached"], s["mean_seconds"],
                                                              s["mean_input_tokens"], s["mean_output_tokens"]), ""]

    L += ["## 3. How many real overlaps each method still finds at its setting", ""]
    if R["person"]:
        rows = []
        for m in ck.METHODS:
            r = R["person"].get(m)
            if r:
                rows.append([ck.NAMES[m], R["proposal_counts"][m], r["real"],
                             "n/a" if not r["estimated_real_among_proposals"] else "%d (%d to %d)" % (
                                 round(r["estimated_real_among_proposals"]["mid"]),
                                 round(r["estimated_real_among_proposals"]["low"]),
                                 round(r["estimated_real_among_proposals"]["high"])),
                             "yes" if R["chance_ok"].get(m) else "no"])
        L += ["PERSON. `Real among labelled` counts pairs; `Estimated real` scales precision to all proposals."]
        L += [""] + table(["Method", "Proposals", "Real among labelled", "Estimated real (range)", "Chance under one?"], rows) + [""]
        L += ["Labelled pairs at or above each level, by what people judged (the sheet's pairs only, so these are "
              "samples, not corpus counts):", ""]
        for m, rws in R["sweep"].items():
            L += ["**%s**" % ck.NAMES[m], ""]
            L += table(["Level", "Corpus pairs", "Chance per run", "Labelled at or above", "of which real", "loose"],
                       [[x["level"], x["corpus_pairs"], x["chance"], x["labelled_at_or_above"], x["labelled_real"],
                         x["labelled_loose"]] for x in rws]) + [""]
    else:
        L += ["Not measured by a person yet. Corpus counts at every setting, and the chance count beside them, are in "
              "section 1.", ""]

    L += ["## 4. Opposite sides on real quotes", ""]
    if R["person"]:
        rows = [[ck.NAMES[m], frac(r["opposite_among_real_or_loose"]), frac(r["opposite_among_real"])]
                for m, r in R["person"].items()]
        L += ["PERSON. Of a method's labelled proposals that a person judged real or loose, how many a person read as "
              "the quote and the priority taking opposite sides (any labeler saying opposite counts).", ""]
        L += table(["Method", "Opposite among real or loose", "Opposite among real"], rows) + [""]
    else:
        L += ["Not measured by a person yet.", ""]
    rows = []
    for m in ck.METHODS:
        r = R["machine"].get(m)
        if r:
            n = r["opposes"] + r["agrees"] + r["mixed"] + r["no_position"]
            rows.append([ck.NAMES[m], n, r["opposes"], r["agrees"], r["mixed"], r["no_position"]])
    L += ["MACHINE: the AI judge's stance reading on each method's proposals it read as some overlap (real or loose):", ""]
    L += table(["Method", "Read as overlap", "opposes", "agrees", "mixed", "no position"], rows) + [""]

    L += ["## 5. How long a label takes, and where labelers differ", ""]
    t = R["timing"]
    if t and t["overall"]:
        o = t["overall"]
        L += ["PERSON. Seconds from a pair appearing to Next, set aside above %d s as idle (%d set aside). Includes "
              "opening a transcript or source when the labeler did. Median %.0f s, mean %.0f s, quartiles %.0f to %.0f "
              "s, 90th percentile %.0f s, over %d labels." % (t["idle_cap_s"], t["set_aside_over_cap"], o["median"],
                                                              o["mean"], o["p25"], o["p75"], o["p90"], o["n"]), ""]
        L += table(["Pairs to judge", "Minutes at the median", "Minutes at the 90th percentile"],
                   [[n, v["median_minutes"], v["p90_minutes"]] for n, v in t["projection"].items()]) + [""]
        L += table(["By the overlap given", "n", "median s", "p90 s"],
                   [[k, v["n"], "%.0f" % v["median"], "%.0f" % v["p90"]] for k, v in sorted(t["by_overlap"].items()) if v]) + [""]
        L += table(["Labeler", "n", "median s", "mean s"],
                   [[k, v["n"], "%.0f" % v["median"], "%.0f" % v["mean"]] for k, v in t["per_labeler"].items() if v]) + [""]
    else:
        L += ["Not measured: no timed label exists (the page records the time of each label).", ""]
    d = R["disagreements"]
    if d:
        for x in d:
            a, b = x["labelers"]
            kap = "n/a" if x["kappa"] is None else "%.2f" % x["kappa"]
            L += ["- %s and %s: %d shared pairs, %d agree on overlap (kappa %s), %d differ%s; on side: %d shared, %d differ." % (
                a, b, x["shared"], x["agree"], kap, len(x["differ"]),
                " (all between neighbouring levels)" if x["differ"] and x["neighbouring_only"] else "",
                x["side_shared"], len(x["side_differ"]))]
            for diff in x["differ"][:20]:
                L += ["  - %s: %s says %s, %s says %s" % (diff["pair"], a, diff[a], b, diff[b])]
        L += [""]
    elif people:
        L += ["One labeler: where two people differ is not measured.", ""]
    else:
        L += ["No labeler: where two people differ is not measured.", ""]
    if R["ai_against_people"]:
        t = R["ai_against_people"]["overlap"]
        L += ["### The AI judge against people", "",
              "Rows are the people's consensus overlap, columns the AI judge's reading, on the labelled pairs it read.", ""]
        L += table(["People", "AI: real", "AI: loose", "AI: none"],
                   [[lv, t[lv].get("real", 0), t[lv].get("loose", 0), t[lv].get("none", 0)] for lv in ("real", "loose", "none")]) + [""]

    L += ["## 6. The blind sheet", "",
          "%d pairs, built %s%s. Pairs per stratum (a pair may sit in several): %s. The sheet shows exact caption words "
          "and donor wording with their sources and nothing about any method; the key to which method each pair was "
          "drawn from is `labelling/sheet-key.json`." % (
              R["sheet"]["pairs"], R["sheet"]["built"], " (reused, not rebuilt)" if R["sheet"]["frozen_reused"] else "",
              ", ".join("%s %d" % kv for kv in R["sheet"]["strata"].items())), ""]
    return "\n".join(L)


def _pair_block(R, ctx, pid, heading):
    qi, pi = ctx["parse"](pid)
    q, p = ctx["quotes"][qi], ctx["priorities"][pi]
    return ["### %s" % heading, "",
            "- Pair id: `%s`" % pid,
            "- Quote, exact raw caption: \"%s\"" % q["text"],
            "- Meeting: %s, %s, caption stamp %s ([transcript](%s), retrieved %s)" % (
                q["meeting_body"], q["meeting_date"], q["start"], q["url"], q["retrieved"]),
            "- Priority (%s, section \"%s\"): \"%s\" ([source](%s), retrieved %s)" % (
                p["donor"], p.get("section") or "", p["text"], p["url"], p["retrieved"])]


def stand_out_markdown(R, ctx):
    L = ["# Matches that stand out: pairs a method proposed and a person judged a real overlap", "",
         "An instance needs all of: a method proposed the pair (not a person); a person who is not the run, and did "
         "not see which method found it, labelled it a real overlap; the quote and the priority take the same side; "
         "the quote is from a real city caption; and the proposing method's chance count at that setting averages under "
         "one pair per run. Generated by `method/run.py`.", ""]
    inst = R["instances"]
    L += ["## Instances (%d)" % len(inst), ""]
    if inst:
        L += ["%d of them have no labeler reading the speaker as someone other than an official." % sum(
            1 for x in inst if x["speaker"] != "other"), ""]
    if not inst:
        L += ["None. " + ("No person has labelled any pair yet." if not R["people"] else
                          "No labelled pair meets every condition."), ""]
    for n, x in enumerate(inst, 1):
        pid = x["pair"]
        L += _pair_block(R, ctx, pid, "Instance %d" % n)
        c = ctx["cons"][pid]
        L += ["- Proposed by: %s" % "; ".join("%s (chance %s pairs per run at its setting; %s)" % (
            ck.NAMES[m], chance_text(R, m), rule(R, m)) for m in x["methods"]),
              "- Labelled by: %s, overlap real, side %s, speaker %s (labelers' own reading)" % (
                  ", ".join(x["labelers"]), c["side"], c["speaker"]),
              "- Label times (s): %s" % ", ".join("%s %.0f" % (w, ctx["people"][w]["ms"][pid] / 1000.0)
                                                  for w in x["labelers"] if pid in ctx["people"][w]["ms"]), ""]
    L += ["## Awaiting a person's label (machine reading only, not instances)", "",
          "Pairs a method with chance under one pair per run proposes and the AI judge reads as a real overlap on the "
          "same side by an official or an unclear speaker. They are shown for whoever picks the next labelling; "
          "**labelers should label the sheet before opening this file.**", ""]
    cand = []
    for pid in sorted(ctx["ai"]):
        if pid in ctx["cons"] or "error" in ctx["ai"][pid] or pid.startswith("NULL-"):
            continue
        a = ctx["ai"][pid]
        ms = [m for m in ck.METHODS if ctx["props"].get(m) and pid in ctx["props"][m] and R["chance_ok"].get(m)]
        if ms and a["overlap"] == "real" and a["stance"] == "agrees" and a["speaker_type"] in ("official", "unclear"):
            cand.append((len(ms), pid, ms))
    cand.sort(key=lambda t: (-t[0], t[1]))
    L += ["%d such pairs; the first 12:" % len(cand), ""]
    for k, (_, pid, ms) in enumerate(cand[:12], 1):
        L += _pair_block(R, ctx, pid, "Candidate %d" % k)
        L += ["- Proposed by: %s" % ", ".join(ck.NAMES[m] for m in ms),
              "- AI reading: %s" % ctx["ai"][pid]["reason"], ""]
    return "\n".join(L)
